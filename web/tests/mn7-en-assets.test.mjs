function readText(filePath) {
  return fs.readFileSync(filePath, 'utf8')
}

function readArrayBuffer(filePath) {
  const buffer = fs.readFileSync(filePath)

  return buffer.buffer.slice(
    buffer.byteOffset,
    buffer.byteOffset + buffer.byteLength
  )
}

function requireNonEmptyFile(filePath) {
  assert.ok(
    fs.existsSync(filePath),
    `Missing required file: ${filePath}`
  )

  const stat = fs.statSync(filePath)

  assert.ok(
    stat.isFile(),
    `Expected a file: ${filePath}`
  )

  assert.ok(
    stat.size > 0,
    `File is empty: ${filePath}`
  )
}

function readAscii(bytes) {
  const zeroIndex = bytes.indexOf(0)

  const end =
    zeroIndex === -1
      ? bytes.length
      : zeroIndex

  return String.fromCharCode(
    ...bytes.slice(0, end)
  )
}

function checksum16(bytes) {
  let checksum = 0

  for (const byte of bytes) {
    checksum += byte
  }

  return checksum & 0xffff
}

function toArrayBuffer(uint8) {
  return uint8.buffer.slice(
    uint8.byteOffset,
    uint8.byteOffset + uint8.byteLength
  )
}

/*
 * Parse the srmodels.bin format generated by
 * WakenetModelPacker.
 */
function parseSrModels(arrayBuffer) {
  const bytes = new Uint8Array(arrayBuffer)
  const view = new DataView(arrayBuffer)

  assert.ok(
    bytes.length >= 4,
    'srmodels.bin is too small'
  )

  const modelCount = view.getUint32(0, true)

  let cursor = 4

  const models = []

  for (let i = 0; i < modelCount; i++) {
    assert.ok(
      cursor + 36 <= bytes.length,
      'Invalid srmodels.bin model header'
    )

    const modelName = readAscii(
      bytes.slice(cursor, cursor + 32)
    )

    cursor += 32

    const fileCount = view.getUint32(
      cursor,
      true
    )

    cursor += 4

    const files = []

    for (let j = 0; j < fileCount; j++) {
      assert.ok(
        cursor + 40 <= bytes.length,
        `Invalid file table for ${modelName}`
      )

      const filename = readAscii(
        bytes.slice(cursor, cursor + 32)
      )

      cursor += 32

      const start = view.getUint32(
        cursor,
        true
      )

      cursor += 4

      const length = view.getUint32(
        cursor,
        true
      )

      cursor += 4

      assert.ok(
        start + length <= bytes.length,
        `${modelName}/${filename} exceeds srmodels.bin`
      )

      files.push({
        filename,
        start,
        length
      })
    }

    models.push({
      name: modelName,
      files
    })
  }

  return {
    modelCount,
    models
  }
}

/*
 * Parse the assets.bin format generated by
 * SpiffsGenerator.
 */
function parseAssetsBin(arrayBuffer) {
  const bytes = new Uint8Array(arrayBuffer)
  const view = new DataView(arrayBuffer)

  assert.ok(
    bytes.length >= 12,
    'assets.bin is too small'
  )

  const totalFiles = view.getUint32(0, true)
  const storedChecksum = view.getUint32(4, true)
  const combinedLength = view.getUint32(8, true)

  assert.ok(
    totalFiles > 0,
    'assets.bin contains no files'
  )

  assert.equal(
    combinedLength,
    bytes.length - 12,
    'assets.bin combined length mismatch'
  )

  const calculatedChecksum = checksum16(
    bytes.slice(12)
  )

  assert.equal(
    calculatedChecksum,
    storedChecksum,
    'assets.bin checksum mismatch'
  )

  const ENTRY_SIZE = 44
  const mmapSize = totalFiles * ENTRY_SIZE

  assert.ok(
    12 + mmapSize <= bytes.length,
    'assets.bin mmap table exceeds image'
  )

  const entries = []

  for (let i = 0; i < totalFiles; i++) {
    const base = 12 + i * ENTRY_SIZE

    const filename = readAscii(
      bytes.slice(base, base + 32)
    )

    const size = view.getUint32(
      base + 32,
      true
    )

    const relativeOffset = view.getUint32(
      base + 36,
      true
    )

    const width = view.getUint16(
      base + 40,
      true
    )

    const height = view.getUint16(
      base + 42,
      true
    )

    const markerOffset =
      12 + mmapSize + relativeOffset

    assert.equal(
      bytes[markerOffset],
      0x5a,
      `${filename}: missing first 0x5A marker`
    )

    assert.equal(
      bytes[markerOffset + 1],
      0x5a,
      `${filename}: missing second 0x5A marker`
    )

    const dataStart = markerOffset + 2
    const dataEnd = dataStart + size

    assert.ok(
      dataEnd <= bytes.length,
      `${filename}: data exceeds assets.bin`
    )

    entries.push({
      filename,
      size,
      width,
      height,
      data: bytes.slice(
        dataStart,
        dataEnd
      )
    })
  }

  return {
    totalFiles,
    checksum: storedChecksum,
    entries
  }
}

/*
 * WakenetModelPacker's production loader uses browser
 * fetch() against:
 *
 * ./static/wakenet_model/...
 * ./static/multinet_model/...
 *
 * In Node/CI we map those same URLs to web/public/static.
 */
async function buildSpeechModel(modelName) {
  const packer = new WakenetModelPacker()

  const originalFetch = globalThis.fetch

  globalThis.fetch = async input => {
    const requested = String(input)

    const relative = requested
      .replace(/^\.\//, '')
      .replace(/\//g, path.sep)

    const filePath = path.resolve(
      PUBLIC_ROOT,
      relative
    )

    const allowedStaticRoot =
      path.resolve(
        PUBLIC_ROOT,
        'static'
      )

    const relativeToStatic =
      path.relative(
        allowedStaticRoot,
        filePath
      )

    assert.ok(
      relativeToStatic &&
      !relativeToStatic.startsWith('..') &&
      !path.isAbsolute(relativeToStatic),
      `Unexpected fetch path: ${requested}`
    )

    if (!fs.existsSync(filePath)) {
      return {
        ok: false,
        status: 404,
        arrayBuffer: async () =>
          new ArrayBuffer(0)
      }
    }

    return {
      ok: true,
      status: 200,
      arrayBuffer: async () =>
        readArrayBuffer(filePath)
    }
  }

  try {
    const loaded =
      await packer.loadModelFromShare(
        modelName
      )

    assert.equal(
      loaded,
      true,
      `Failed to load model: ${modelName}`
    )

    const binary =
      packer.packModels()

    const stats =
      packer.getStats()

    return {
      binary,
      stats
    }
  } finally {
    globalThis.fetch = originalFetch
  }
}

async function main() {
  console.log('')
  console.log(
    '=== MN7 English / Hey Spooky Asset Test ==='
  )
  console.log('')

  fs.rmSync(
    OUTPUT_DIR,
    {
      recursive: true,
      force: true
    }
  )

  fs.mkdirSync(
    OUTPUT_DIR,
    {
      recursive: true
    }
  )

  /*
   * Verify the real MN7 files in this repository.
   */
  assert.ok(
    fs.existsSync(MN7_DIR),
    `Missing MN7 directory: ${MN7_DIR}`
  )

  for (const filename of REQUIRED_MN7_FILES) {
    requireNonEmptyFile(
      path.join(
        MN7_DIR,
        filename
      )
    )
  }

  pass(
    'MN7 English model files exist'
  )

  const modelInfo = readText(
    path.join(
      MN7_DIR,
      '_MODEL_INFO_'
    )
  )

  assert.match(
    modelInfo,
    /MN7/i,
    '_MODEL_INFO_ does not identify MN7'
  )

  assert.match(
    modelInfo,
    /english/i,
    '_MODEL_INFO_ does not identify English'
  )

  pass(
    'MN7 metadata identifies an English MN7 model'
  )

  /*
   * Verify FST resources.
   */
  for (const filename of REQUIRED_FST_FILES) {
    requireNonEmptyFile(
      path.join(
        FST_DIR,
        filename
      )
    )
  }

  pass(
    'MultiNet FST resources exist'
  )

  /*
   * Verify locale keys.
   */
  for (const filename of LOCALE_FILES) {
    const locale = JSON.parse(
      readText(
        path.join(
          SRC_ROOT,
          'locales',
          filename
        )
      )
    )

    for (const key of [
      'mn6cn',
      'mn6en',
      'mn7cn',
      'mn7en'
    ]) {
      assert.equal(
        typeof locale.wakewordConfig?.[key],
        'string',
        `${filename}: wakewordConfig.${key} is missing`
      )

      assert.ok(
        locale.wakewordConfig[key].trim(),
        `${filename}: wakewordConfig.${key} is empty`
      )
    }
  }

  pass(
    'All registered locale files contain MN6/MN7 labels'
  )

  /*
   * Build the stock VoCat WakeNet9 model.
   */
  const stock =
    await buildSpeechModel(
      STOCK_MODEL
    )

  fs.writeFileSync(
    path.join(
      OUTPUT_DIR,
      'stock-vocat-srmodels.bin'
    ),
    Buffer.from(stock.binary)
  )

  const stockParsed =
    parseSrModels(
      stock.binary
    )

  assert.deepEqual(
    stockParsed.models.map(
      model => model.name
    ),
    [
      STOCK_MODEL
    ],
    'Stock VoCat package contains unexpected models'
  )

  pass(
    'Stock VoCat WakeNet9 package generated successfully'
  )

  /*
   * Build MN7 English + FST.
   */
  const spooky =
    await buildSpeechModel(
      SPOOKY_MODEL
    )

  fs.writeFileSync(
    path.join(
      OUTPUT_DIR,
      'hey-spooky-srmodels.bin'
    ),
    Buffer.from(spooky.binary)
  )

  const spookyParsed =
    parseSrModels(
      spooky.binary
    )

  const mn7Model =
    spookyParsed.models.find(
      model =>
        model.name === SPOOKY_MODEL
    )

  assert.ok(
    mn7Model,
    'MN7 English model missing from srmodels.bin'
  )

  assert.deepEqual(
    mn7Model.files
      .map(file => file.filename)
      .sort(),
    [
      '_MODEL_INFO_',
      'mn7_data',
      'mn7_index',
      'vocab'
    ].sort(),
    'MN7 English packaged files are incorrect'
  )

  const fstModel =
    spookyParsed.models.find(
      model =>
        model.name === 'fst'
    )

  assert.ok(
    fstModel,
    'FST model missing from MN7 package'
  )

  assert.ok(
    fstModel.files.some(
      file =>
        file.filename ===
        'commands_en.txt'
    ),
    'English FST commands are missing'
  )

  pass(
    'MN7 English + FST package generated successfully'
  )

  /*
   * Compare generated model packages.
   */
  assert.ok(
    spooky.binary.byteLength >
      stock.binary.byteLength,
    'Expected MN7 + FST package to be larger than stock WakeNet9'
  )

  const comparison = {
    stock: {
      engine: 'WakeNet9',
      model: STOCK_MODEL,
      bytes:
        stock.binary.byteLength,
      models:
        stockParsed.models.map(
          model => model.name
        )
    },

    spooky: {
      engine: 'MultiNet7',
      model: SPOOKY_MODEL,
      command: 'hey spooky',
      bytes:
        spooky.binary.byteLength,
      models:
        spookyParsed.models.map(
          model => model.name
        )
    },

    differenceBytes:
      spooky.binary.byteLength -
      stock.binary.byteLength
  }

  fs.writeFileSync(
    path.join(
      OUTPUT_DIR,
      'model-comparison.json'
    ),
    JSON.stringify(
      comparison,
      null,
      2
    )
  )

  console.log('')
  console.log(
    'Generated model comparison:'
  )

  console.log(
    `  Stock VoCat: ${comparison.stock.bytes} bytes`
  )

  console.log(
    `  Hey Spooky : ${comparison.spooky.bytes} bytes`
  )

  console.log(
    `  Difference : ${comparison.differenceBytes} bytes`
  )

  console.log('')

  /*
   * Build the index.json configuration for Hey Spooky.
   *
   * This mirrors the transformation currently performed
   * by AssetsBuilder.generateIndexJson().
   */
  const custom = {
    name: 'Hey Spooky',
    command: 'hey spooky',
    model: SPOOKY_MODEL,
    threshold: 20,
    duration: 3000
  }

  const indexJson = {
    version: 1,

    chip_model:
      'esp32s3',

    display_config: {
      width: 360,
      height: 360,
      monochrome: false,
      color: 'RGB565'
    },

    srmodels:
      'srmodels.bin',

    multinet_model: {
      language:
        custom.model.includes('_en')
          ? 'en'
          : 'cn',

      duration:
        custom.duration ||
        3000,

      threshold:
        custom.threshold /
        100.0,

      commands: [
        {
          command:
            custom.command,

          text:
            custom.name,

          action:
            'wake'
        }
      ]
    }
  }

  assert.deepEqual(
    indexJson.multinet_model,
    {
      language: 'en',
      duration: 3000,
      threshold: 0.2,

      commands: [
        {
          command: 'hey spooky',
          text: 'Hey Spooky',
          action: 'wake'
        }
      ]
    }
  )

  pass(
    'Hey Spooky MultiNet configuration is correct'
  )

  /*
   * Generate a real assets.bin using the project's
   * SpiffsGenerator.
   */
  const generator =
    new SpiffsGenerator()

  const indexBytes =
    new TextEncoder().encode(
      JSON.stringify(
        indexJson,
        null,
        2
      )
    )

  generator.addFile(
    'index.json',
    toArrayBuffer(indexBytes)
  )

  generator.addFile(
    'srmodels.bin',
    spooky.binary
  )

  const assetsBin =
    await generator.generate()

  assert.ok(
    assetsBin.byteLength > 0,
    'Generated assets.bin is empty'
  )

  fs.writeFileSync(
    path.join(
      OUTPUT_DIR,
      'hey-spooky-assets.bin'
    ),
    Buffer.from(assetsBin)
  )

  pass(
    `Generated assets.bin (${assetsBin.byteLength} bytes)`
  )

  /*
   * Parse assets.bin back and verify its checksum,
   * mapping table, index.json and srmodels.bin.
   */
  const parsedAssets =
    parseAssetsBin(
      assetsBin
    )

  const indexEntry =
    parsedAssets.entries.find(
      entry =>
        entry.filename ===
        'index.json'
    )

  const srmodelsEntry =
    parsedAssets.entries.find(
      entry =>
        entry.filename ===
        'srmodels.bin'
    )

  assert.ok(
    indexEntry,
    'Generated assets.bin is missing index.json'
  )

  assert.ok(
    srmodelsEntry,
    'Generated assets.bin is missing srmodels.bin'
  )

  pass(
    'Generated assets.bin contains index.json and srmodels.bin'
  )

  /*
   * Verify the index after extracting it from the
   * generated assets.bin itself.
   */
  const packagedIndex =
    JSON.parse(
      new TextDecoder().decode(
        indexEntry.data
      )
    )

  assert.equal(
    packagedIndex.chip_model,
    'esp32s3'
  )

  assert.equal(
    packagedIndex.display_config.width,
    360
  )

  assert.equal(
    packagedIndex.display_config.height,
    360
  )

  assert.equal(
    packagedIndex.srmodels,
    'srmodels.bin'
  )

  assert.deepEqual(
    packagedIndex.multinet_model,
    {
      language: 'en',
      duration: 3000,
      threshold: 0.2,

      commands: [
        {
          command: 'hey spooky',
          text: 'Hey Spooky',
          action: 'wake'
        }
      ]
    }
  )

  fs.writeFileSync(
    path.join(
      OUTPUT_DIR,
      'hey-spooky-index.json'
    ),
    JSON.stringify(
      packagedIndex,
      null,
      2
    )
  )

  pass(
    'Packaged index.json contains Hey Spooky configuration'
  )

  /*
   * Parse srmodels.bin after extracting it back out
   * of the finished assets.bin.
   */
  const finalSrmodels =
    parseSrModels(
      toArrayBuffer(
        srmodelsEntry.data
      )
    )

  assert.ok(
    finalSrmodels.models.some(
      model =>
        model.name ===
        SPOOKY_MODEL
    ),
    'Final assets.bin lost mn7_en'
  )

  assert.ok(
    finalSrmodels.models.some(
      model =>
        model.name === 'fst'
    ),
    'Final assets.bin lost FST model'
  )

  pass(
    'Final assets.bin contains intact MN7 English + FST models'
  )

  console.log('')
  console.log(
    'ALL MN7 ENGLISH / HEY SPOOKY ASSET TESTS PASSED'
  )
  console.log('')
}

main().catch(error => {
  console.error('')
  console.error(
    'MN7 ENGLISH ASSET TEST FAILED'
  )
  console.error('')
  console.error(
    error.stack || error
  )

  process.exitCode = 1
})
